ALTER TABLE public.students ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.game_sessions ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Allow public read is_types" ON public.is_types;
CREATE POLICY "Allow public read is_types" ON public.is_types FOR SELECT USING (true);

DROP POLICY IF EXISTS "Allow public read indicators" ON public.curriculum_indicators;
CREATE POLICY "Allow public read indicators" ON public.curriculum_indicators FOR SELECT USING (true);

DROP POLICY IF EXISTS "Allow public read questions" ON public.questions;
CREATE POLICY "Allow public read questions" ON public.questions FOR SELECT USING (true);

DROP POLICY IF EXISTS "Allow public insert questions" ON public.questions;
CREATE POLICY "Allow public insert questions" ON public.questions FOR INSERT WITH CHECK (true);

DROP POLICY IF EXISTS "Allow public read students" ON public.students;
CREATE POLICY "Allow public read students" ON public.students FOR SELECT USING (true);

DROP POLICY IF EXISTS "Allow public upsert students" ON public.students;
CREATE POLICY "Allow public upsert students" ON public.students FOR INSERT WITH CHECK (true);

DROP POLICY IF EXISTS "Allow public update students" ON public.students;
CREATE POLICY "Allow public update students" ON public.students FOR UPDATE USING (true);

DROP POLICY IF EXISTS "Allow public read game_sessions" ON public.game_sessions;
CREATE POLICY "Allow public read game_sessions" ON public.game_sessions FOR SELECT USING (true);

DROP POLICY IF EXISTS "Allow public insert game_sessions" ON public.game_sessions;
CREATE POLICY "Allow public insert game_sessions" ON public.game_sessions FOR INSERT WITH CHECK (true);


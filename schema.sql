-- 1. ตารางประเภทของระบบสารสนเทศ 6 ประเภท (is_types)
CREATE TABLE IF NOT EXISTS public.is_types (
  code TEXT PRIMARY KEY,
  name_en TEXT NOT NULL,
  name_th TEXT NOT NULL,
  org_level TEXT NOT NULL,
  svg_path TEXT NOT NULL,
  keywords JSONB NOT NULL DEFAULT '[]'::jsonb,
  input_desc TEXT NOT NULL,
  process_desc TEXT NOT NULL,
  output_desc TEXT NOT NULL,
  example_desc TEXT NOT NULL
);

-- 2. ตารางตัวชี้วัดหลักสูตรแกนกลาง พ.ศ. 2560 (curriculum_indicators)
CREATE TABLE IF NOT EXISTS public.curriculum_indicators (
  code TEXT PRIMARY KEY,
  standard_name TEXT NOT NULL,
  description TEXT NOT NULL,
  uni_mapping TEXT NOT NULL
);

-- 3. ตารางคลังข้อสอบและสถานการณ์จำลอง (questions)
CREATE TABLE IF NOT EXISTS public.questions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  stage TEXT NOT NULL,
  org_name TEXT NOT NULL,
  indicator_code TEXT NOT NULL,
  title TEXT NOT NULL,
  scenario_desc TEXT NOT NULL,
  user_role TEXT NOT NULL,
  process_type TEXT NOT NULL,
  output_type TEXT NOT NULL,
  hint_text TEXT NOT NULL,
  correct_code TEXT NOT NULL,
  explanation TEXT NOT NULL,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. ตารางข้อมูลนักศึกษาชั้นปีที่ 2 (students)
CREATE TABLE IF NOT EXISTS public.students (
  student_id TEXT PRIMARY KEY,
  full_name TEXT NOT NULL,
  year_level INT DEFAULT 2,
  faculty TEXT DEFAULT 'เทคโนโลยีสารสนเทศ / ครุศาสตร์',
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 5. ตารางบันทึกผลการเล่นและ Leaderboard (game_sessions)
CREATE TABLE IF NOT EXISTS public.game_sessions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id TEXT NOT NULL,
  full_name TEXT NOT NULL,
  total_score INT NOT NULL DEFAULT 0,
  accuracy_pct INT NOT NULL DEFAULT 0,
  rank_title TEXT NOT NULL DEFAULT 'Junior IS Learner',
  stage1_done INT NOT NULL DEFAULT 0,
  stage2_done INT NOT NULL DEFAULT 0,
  stage3_done INT NOT NULL DEFAULT 0,
  type_stats_json JSONB DEFAULT '{}'::jsonb,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

